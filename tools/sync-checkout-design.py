#!/usr/bin/env python3
"""Export the approved local WHMCS checkout style and current site icons for WooCommerce."""
from pathlib import Path
import hashlib
import json
import sys

root = Path(__file__).resolve().parents[1]
source = root.parent / 'boltutil-whmcs/modules/gateways/boltutil/assets/checkout.css'
site = root.parent / 'bolt-util-frontend'
check = '--check' in sys.argv

def write(path, data):
    if check:
        assert path.read_bytes() == data, f'Checkout standard drift: {path.relative_to(root)}'
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

snapshot = root / 'assets/checkout-standard.css'
if source.is_file():
    write(snapshot, source.read_bytes())
css = snapshot.read_text()
scope = '.boltutil-checkout-standard'
mapping = {
    ':root': scope,
    '*': scope + ', ' + scope + ' *',
    'body': scope,
    'h1': scope + ' .checkout-title',
    '.asset-switch button': scope + ' .asset-switch :is(button, .boltutil-token-option)',
    '.asset-switch button[aria-selected="true"]': scope + ' .asset-switch :is(button[aria-selected="true"], .boltutil-token-option:has(input:checked))',
    '.asset-switch button:focus-visible': scope + ' .asset-switch :is(button:focus-visible, .boltutil-token-option:has(input:focus-visible))',
}

def scoped(text):
    out = ''
    while text.strip():
        start = text.find('{')
        assert start >= 0
        prelude = text[:start]
        # Preserve comments separately from the selector.
        comment = ''
        while '/*' in prelude:
            left, rest = prelude.split('/*', 1)
            body, right = rest.split('*/', 1)
            comment += left + '/*' + body + '*/\n'
            prelude = right
        selector = prelude.strip()
        level = 1
        end = start + 1
        while level:
            if text[end] == '{': level += 1
            if text[end] == '}': level -= 1
            end += 1
        body = text[start + 1:end - 1]
        text = text[end:]
        if selector.startswith('@'):
            out += comment + selector + ' {\n' + scoped(body) + '}\n'
        elif selector != 'html':
            selectors = [mapping.get(s.strip(), scope + ' ' + s.strip()) for s in selector.split(',')]
            out += comment + ', '.join(selectors) + ' {' + body + '}\n'
    return out

write(root / 'assets/checkout-base.css', ('/* Generated by tools/sync-checkout-design.py; edit the approved standard, not this scoped export. */\n' + scoped(css)).encode())
sources = {**{f'chains/{name}': f'public/assets/chains/{name}' for name in ('tron.png', 'ethereum.png', 'bnb-chain.svg', 'polygon.svg', 'solana.png', 'base.svg')},
           **{f'tokens/{name}': f'app/assets/tokens/{name}' for name in ('usdt.svg', 'usdc.svg')}}
manifest = []
if site.is_dir():
    for target, original in sources.items():
        data = (site / original).read_bytes()
        write(root / 'assets' / target, data)
        manifest.append({'file': 'assets/' + target, 'projectSource': 'bolt-util-frontend/' + original, 'sha256': hashlib.sha256(data).hexdigest(), 'modification': 'none', 'license': 'original-brand-terms'})
    write(root / 'assets/checkout-sources.json', (json.dumps({'styleSource': 'boltutil-whmcs/modules/gateways/boltutil/assets/checkout.css', 'styleSha256': hashlib.sha256(css.encode()).hexdigest(), 'images': manifest}, indent=2) + '\n').encode())
    for name in ('ASSETS-NOTICE.txt', 'official-sources.json'):
        write(root / 'assets/chains' / name, (site / 'public/assets/chains' / name).read_bytes())
    write(root / 'assets/tokens/project-sources.json', (site / 'app/assets/tokens/sources.json').read_bytes())
print('PASS checkout CSS export and current project original images' if check else 'Synced checkout CSS standard and eight unmodified site images')
